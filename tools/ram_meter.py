#!/usr/bin/env python3
"""RAM meter, static half: compile the engine for the RP2040 and size every global.

Compiles each engine/*.c with the Pico toolchain's arm-none-eabi-gcc for a
Cortex-M0+ (no link needed), then reads symbol sizes with nm. Reports
.bss/.data (RAM) per file and the biggest symbols, which is the hit list for
shrinking Quake. Dynamic memory (hunk, zone, cache) is the runtime half: the
PC build's title bar and its `qog_mem` console command.

    python tools/ram_meter.py                 # writes build/ram-report.md
    python tools/ram_meter.py --top 50 --budget-kb 245

Standard library only.
"""
import argparse
import os
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TOOLCHAIN = os.path.join(os.path.expanduser("~"), ".pico-sdk", "toolchain", "15_2_Rel1", "bin")
EXE = ".exe" if os.name == "nt" else ""
GCC = os.path.join(TOOLCHAIN, "arm-none-eabi-gcc" + EXE)
NM = os.path.join(TOOLCHAIN, "arm-none-eabi-nm" + EXE)
# Same files the PC build compiles (pc/CMakeLists.txt): the real mixer, not the null stub.
EXCLUDE = {"snd_null.c"}
CFLAGS = ["-std=gnu11", "-mcpu=cortex-m0plus", "-mthumb", "-Os", "-fno-common", "-ffunction-sections",
          "-fdata-sections", "-w", "-Wno-implicit-function-declaration", "-DQOG_RP2040_METER", "-DQOG_SINGLE_PLAYER", "-DQOG_EDICT_MARGIN=128", "-DQOG_MAX_MOD_KNOWN=192", "-DQOG_MAX_PARTICLES=512", "-DQOG_CON_TEXTSIZE=4096", "-DQOG_KEY_HISTORY=8", "-DQOG_LOOP_SERVER_RX=2048", "-DQOG_MAX_MSGLEN=6500", "-DQOG_SIGNON_SIZE=6500", "-DQOG_LOOP_CLIENT_RX=7532", "-DQOG_LOCALSTACK_FROM_PROGS", "-I", os.path.join(ROOT, "engine")]
RAM_TYPES = set("bBdD")   # bss and data, local and global


def compile_and_size(src, obj):
    r = subprocess.run([GCC, *CFLAGS, "-c", src, "-o", obj], capture_output=True, text=True)
    if r.returncode != 0:
        return None, r.stderr.strip().splitlines()[:3]
    out = subprocess.run([NM, "-S", "--size-sort", obj], capture_output=True, text=True, check=True).stdout
    syms = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 4 and parts[2] in RAM_TYPES:
            syms.append((int(parts[1], 16), parts[3], parts[2] in "dD"))
    return syms, None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--top", type=int, default=40, help="how many of the biggest symbols to list")
    ap.add_argument("--budget-kb", type=float, default=245.0, help="RAM available to Quake")
    ap.add_argument("-o", "--out", default=os.path.join(ROOT, "build", "ram-report.md"))
    a = ap.parse_args(argv)
    if not os.path.exists(GCC):
        sys.exit("arm-none-eabi-gcc not found at %s (Pico VS Code extension toolchain)" % GCC)

    srcs = sorted(f for f in os.listdir(os.path.join(ROOT, "engine")) if f.endswith(".c") and f not in EXCLUDE)
    per_file, all_syms, failures = [], [], []
    with tempfile.TemporaryDirectory() as tmp:
        for f in srcs:
            syms, err = compile_and_size(os.path.join(ROOT, "engine", f), os.path.join(tmp, f + ".o"))
            if syms is None:
                failures.append((f, err))
                continue
            per_file.append((sum(s for s, _, _ in syms), f))
            all_syms += [(s, n, f) for s, n, _ in syms]

    total = sum(s for s, _ in per_file)
    budget = a.budget_kb * 1024
    lines = ["# Static RAM report (engine compiled for Cortex-M0+)", "",
             "Generated by `tools/ram_meter.py`. Covers globals and fixed arrays (.bss + .data) of the engine only.",
             "Dynamic memory (hunk, zone, cache) is extra and is shown by the PC build (`qog_mem`).", "",
             "| | KB |", "| --- | ---: |",
             "| **Engine static RAM** | **%.1f** |" % (total / 1024),
             "| Budget for all of Quake | %.1f |" % a.budget_kb,
             "| Left for dynamic memory and stack | %.1f |" % ((budget - total) / 1024), ""]
    if failures:
        lines += ["## Files that did not compile for ARM (not counted)", ""]
        lines += ["- `%s`: %s" % (f, " / ".join(e)) for f, e in failures] + [""]
    lines += ["## Biggest symbols", "", "| KB | Symbol | File |", "| ---: | --- | --- |"]
    lines += ["| %.1f | `%s` | %s |" % (s / 1024, n, f) for s, n, f in sorted(all_syms, reverse=True)[:a.top]]
    lines += ["", "## Per file", "", "| KB | File |", "| ---: | --- |"]
    lines += ["| %.1f | %s |" % (s / 1024, f) for s, f in sorted(per_file, reverse=True) if s]
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print("engine static RAM %.1f KB of %.1f KB budget (%d files, %d failed) -> %s"
          % (total / 1024, a.budget_kb, len(per_file), len(failures), a.out))
    for s, n, f in sorted(all_syms, reverse=True)[:12]:
        print("  %8.1f KB  %-28s %s" % (s / 1024, n, f))
    return 0


if __name__ == "__main__":
    sys.exit(main())
